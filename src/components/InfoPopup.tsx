// =========================================================
// Попап-привітання: правила гри + поле нікнейма (localStorage) + "Почати".
// Відкривається при заході на сайт і за кнопкою "Правила" в хедері.
// Усі числа (бали, ціни каменів, ліміти) беруться з налаштувань/констант —
// текст не розходиться з адмінкою.
// Під час активного забігу (є спроби) нік заблоковано — зміна ніка посеред
// забігу розщепила б результат гравця на два записи ладдера.
// =========================================================

import { useState } from 'react';
import Modal from './Modal';
import type { LadderSettings } from '../data/ladder';
import { MAX_ATTEMPTS, MIN_ATTEMPTS_FOR_RESET } from '../lib/ladderEngine';

export default function InfoPopup({
  nickname,
  nickLocked,
  settings,
  onStart,
  onClose,
}: {
  nickname: string;
  /** Активний забіг: нік міняти не можна. */
  nickLocked: boolean;
  settings: LadderSettings;
  onStart: (nickname: string) => void;
  /** Не передано (перший вхід без ніка) — попап закривається лише "Почати". */
  onClose?: () => void;
}) {
  const [value, setValue] = useState(nickname);
  const trimmed = value.trim();
  /** Повертається сюди пізніше (напр. за кнопкою "Правила" в хедері), а не
   * зайшов уперше — у нього вже є збережений нік. */
  const isReturning = !!nickname;
  const buttonLabel = !isReturning ? 'Почати' : trimmed === nickname ? 'Закрити' : 'Зберегти нік';
  const s = settings;

  return (
    <Modal width={600} onClose={onClose}>
      <div className="modal-head">
        <img
          src={import.meta.env.BASE_URL + 'assets/thunder-hero.gif'}
          alt=""
          style={{ width: 40, height: 'auto', flex: '0 0 auto', borderRadius: 'var(--radius)', filter: 'drop-shadow(0 4px 12px rgba(216, 31, 31, 0.5))' }}
        />
        <h3 style={{ margin: 0 }}>Ладдер страждання</h3>
      </div>
      <div className="modal-body rules">
        <section>
          <h4>Суть</h4>
          <p>
            Точиш предмет <b>міражем</b> — безкоштовно, кожен успіх дає <b>{s.pointsPerSuccess} балів</b>.
            Провал міража скидає рівень у <b>+0</b>. Бали витрачаєш на камені-помічники з кращими шансами.
            Мета — якнайвищий рівень за якнайменше спроб.
          </p>
        </section>

        <section>
          <h4>Два предмети</h4>
          <ul>
            <li><b>Основна</b> — та, що зараз вища за рівнем. Саме її рівень іде в ладдер.</li>
            <li><b>Підставна</b> — друга. Успіх на ній дає <b>{s.decoyPointsPerSuccess} балів</b> (замість {s.pointsPerSuccess}); камені коштують стільки ж.</li>
            <li>Переросла основну — <b>міняються ролями</b> (рокіровка). При рівних рівнях ролі не міняються.</li>
            <li>Спроби на підставній <b>рахуються в ліміт</b> так само — ритуал коштує бюджету.</li>
            <li>Класика «підставної шмотки»: ловиш на ній серію мінусів, тоді тиснеш основну. Гра ритуал не підсилює —
              ГВЧ незалежний — але чесно <b>покаже у фіналі</b>, чи воно працювало.</li>
          </ul>
        </section>

        <section>
          <h4>Камені</h4>
          <ul>
            <li><b>Небеска</b> — {s.skyCost} балів, кращий шанс; провал → <b>+0</b>.</li>
            <li><b>Підземка</b> — {s.underCost} балів; провал → лише <b>−1</b>.</li>
            <li><b>Світобудова</b> — {s.worldCost} балів; провал <b>не чіпає</b> рівень, але шанс угорі мізерний.</li>
            <li>На +0 платний камінь — марнотратство: провал і так лишає в нулі, міраж робить те саме безкоштовно.</li>
          </ul>
        </section>

        <section>
          <h4>Забіг</h4>
          <ul>
            <li>Ліміт — <b>{MAX_ATTEMPTS} спроб</b> на обидва предмети разом. Вичерпав — результат сам іде в ладдер, лічильники скидаються.</li>
            <li><b>«Внести в ладдер»</b> — коли завгодно. Кращий за твій попередній результат → зараховано, лічильники скинуто.
              Не кращий → нічого не втрачаєш, забіг просто триває.</li>
            <li><b>«Скинути прогрес»</b> без внесення — лише після <b>{MIN_ATTEMPTS_FOR_RESET} спроб</b>, щоб не перекидати невдалий старт.</li>
            <li>Нік заблоковано на час забігу. Прогрес переживає перезавантаження сторінки.</li>
          </ul>
        </section>

        <section>
          <h4>Рейтинг</h4>
          <p>
            Спершу <b>найвищий рівень</b>; за однакового — хто дійшов за <b>менше спроб</b>; далі — <b>більше балів</b>.
            Сервер перевіряє всю історію спроб — підробити результат не вийде, а от отримати титул
            «Спійманий на гарячому» — цілком.
          </p>
        </section>

        <section>
          <h4>Фінал забігу</h4>
          <ul>
            <li><b>Титули</b> — понад 50, від «RNG GOD» до «ЖЕРТВИ МАРКЕТИНГУ»; частина — з твоєю особистою
              сигнатурою ритуалу (наприклад «КУЛЬТ ‹−−+›»). Підказка на титулі пояснює, за що.</li>
            <li><b>Статистика</b> — стріки, падіння, удача (успіхи проти очікуваних за шансами), агресія
              (скільки рівнів ставиш на кін), графік подорожі, Hall of Shame.</li>
            <li><b>Ритуал</b> — твій патерн підставної, школа (холодна серія / гаряча рука) і головне:
              удача з ритуалом проти удачі без нього. Числа, а не обіцянки.</li>
          </ul>
        </section>

        <section>
          <h4>Спецнагороди</h4>
          <p>
            На головній — найкращі за окремими статами серед усіх гравців (не лише топ-10): найшвидший пік,
            найудачливіший, найкращий стрік, найболючіше падіння, найагресивніший, найбільше поїздок у нуль…
            Оновлюються автоматично після кожного внесеного результату.
          </p>
        </section>

        <label className="field">
          <span>Нікнейм</span>
          <input
            type="text"
            autoFocus={!nickLocked}
            maxLength={40}
            placeholder="Твій нік для ладдера"
            value={value}
            disabled={nickLocked}
            onChange={(e) => setValue(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && trimmed && onStart(trimmed)}
          />
          {nickLocked && (
            <span className="hint" style={{ margin: '4px 0 0' }}>
              Нік заблоковано до кінця поточного забігу — внеси результат або скинь прогрес, щоб змінити.
            </span>
          )}
        </label>
      </div>
      <div className="modal-foot">
        <button
          type="button"
          className="btn btn-primary btn-lg"
          style={{ width: '100%' }}
          disabled={!trimmed}
          onClick={() => onStart(trimmed)}
        >
          {buttonLabel}
        </button>
      </div>
    </Modal>
  );
}
